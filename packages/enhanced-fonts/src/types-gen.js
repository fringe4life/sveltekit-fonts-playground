import fs from 'node:fs';
import path from 'node:path';

/**
 * @param {Array<{ cssVariable: string }>} families
 * @param {string} out_file
 */
export function write_css_variable_types(families, out_file) {
	const vars = [...new Set(families.map((family) => family.cssVariable))];
	const fields = vars.map((value) => `\t\t'${value}': true;`).join('\n');

	fs.mkdirSync(path.dirname(out_file), { recursive: true });
	fs.writeFileSync(
		out_file,
		`// Generated by @sveltejs/enhanced-fonts. Do not edit.\n` +
			`declare module '@sveltejs/enhanced-fonts' {\n` +
			`\tinterface ConfiguredFontCssVariables {\n` +
			(fields ? `${fields}\n` : '') +
			`\t}\n` +
			`}\n` +
			`export {};\n`
	);
}
